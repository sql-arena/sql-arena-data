/** A slice of the sessions of one day, first to last - 1, as agenttelemetry/s3tables.py plan writes it. */
export interface Chunk {
	id: string;
	day: number;
	first: number;
	last: number;
}

export interface Plan {
	sf: number;
	namespace: string;
	table_bucket: string;
	days: number;
	sessions: number;
	sessions_per_chunk: number;
	tables: string[];
	/** Where each table keeps its data files, which workers write into. */
	locations: Record<string, string>;
	chunks: Chunk[];
}

/** A parquet file a worker wrote into a table's storage, holding one partition: a day, as days since 1970-01-01. */
export interface DataFile {
	path: string;
	size: number;
	rows: number;
	partition: number[];
}

/** A worker wrote a chunk's tables as parquet files into their storage, not yet part of the tables. */
export interface Staged {
	event: 'staged';
	time: string;
	chunk: string;
	worker: string;
	files: Record<string, DataFile[]>;
	generate_seconds: number;
	write_seconds: number;
}

/** The coordinator appended the staged files of chunks to a table, in one commit. */
export interface Committed {
	event: 'committed';
	time: string;
	table: string;
	chunks: string[];
	rows: number;
	/** As text, as snapshot ids do not fit a double. */
	snapshot: string;
	seconds: number;
}

export interface Failure {
	event: 'failed';
	time: string;
	chunk: string;
	worker: string;
	error: string;
}

/** A commit of a table failed; its chunks wait for the next. */
export interface CommitFailure {
	event: 'commit failed';
	time: string;
	table: string;
	chunks: string[];
	error: string;
}

export type LedgerRecord = Staged | Committed | Failure | CommitFailure;

export interface Task {
	sf: number;
	days: number;
	tables: string[];
	chunk: Chunk;
	lease: string;
	locations: Record<string, string>;
}

/** Staged files of chunks to append to one table in one commit. */
export interface Batch {
	table: string;
	chunks: string[];
	files: DataFile[];
	rows: number;
}

export interface QueueStatus {
	chunks: number;
	committed: number;
	staged: number;
	leased: number;
	failed: number;
	rows: Record<string, number>;
	chunksPerMinute?: number;
	remainingMinutes?: number;
	averageSeconds?: { generate: number; write: number };
	commits: { table: string; commits: number; averageChunks: number; averageSeconds: number }[];
	failures: (Failure | CommitFailure)[];
}

/** A lease ends when its worker has not staged the chunk for this long, and the chunk goes back to the queue. */
export const LEASE_MS = 30 * 60_000;
export const MAX_ATTEMPTS = 3;
/** Workers get no new chunk while this many wait to be committed, so a stalled commit leaves few files behind. */
export const MAX_STAGED = 400;
const RATE_WINDOW_MS = 10 * 60_000;
const RECENT = 200;

interface Lease {
	lease: string;
	worker: string;
	expires: number;
}

/**
 * The chunks of one run: generated by workers under a lease, staged as parquet, then committed by the coordinator
 * in batches, one table at a time per batch.
 */
export class WorkQueue {
	readonly plan: Plan;
	private readonly chunks = new Map<string, Chunk>();
	private readonly staged = new Map<string, Staged>();
	private readonly committed = new Map<string, Set<string>>();
	private readonly waiting = new Map<string, string[]>();
	private readonly committing = new Set<string>();
	private readonly leases = new Map<string, Lease>();
	private readonly attempts = new Map<string, number>();
	private readonly failed = new Set<string>();
	private readonly pending: string[] = [];
	private head = 0;
	private complete = 0;
	private readonly rows: Record<string, number> = {};
	private readonly completions: number[] = [];
	private readonly recentStaged: Staged[] = [];
	private readonly recentCommits: Committed[] = [];
	private readonly failures: (Failure | CommitFailure)[] = [];

	constructor(
		plan: Plan,
		ledger: LedgerRecord[],
		private readonly newId: () => string
	) {
		this.plan = plan;
		for (const chunk of plan.chunks) this.chunks.set(chunk.id, chunk);
		for (const table of plan.tables) this.waiting.set(table, []);
		for (const record of ledger) {
			if (record.event === 'staged') this.recordStaged(record);
			else if (record.event === 'committed') this.recordCommitted(record, Date.parse(record.time));
			else if (record.event === 'failed') this.recordFailure(record);
			else this.failures.push(record);
		}
		for (const chunk of plan.chunks)
			if (!this.staged.has(chunk.id) && !this.failed.has(chunk.id)) this.pending.push(chunk.id);
	}

	/** The next chunk for worker, or undefined when none is left or too many wait to be committed. */
	lease(worker: string, now: number): Task | undefined {
		this.reclaim(now);
		if (this.staged.size - this.complete >= MAX_STAGED) return undefined;
		while (this.head < this.pending.length) {
			const id = this.pending[this.head++];
			if (this.staged.has(id) || this.failed.has(id) || this.leases.has(id)) continue;
			const lease = this.newId();
			this.leases.set(id, { lease, worker, expires: now + LEASE_MS });
			const { sf, days, tables, locations } = this.plan;
			return { sf, days, tables, chunk: this.chunks.get(id)!, lease, locations };
		}
		return undefined;
	}

	/**
	 * Takes a staged chunk; false from an old lease, whose files are never committed. Files must lie in their table's
	 * storage, as the commit adds whatever path it is given.
	 */
	stage(lease: string, staged: Staged): boolean {
		const held = this.leases.get(staged.chunk);
		if (!held || held.lease !== lease) return false;
		const missing = this.plan.tables.filter((t) => !staged.files[t]?.length);
		if (missing.length) throw new Error(`${staged.chunk} has no files of ${missing.join(', ')}`);
		for (const table of this.plan.tables)
			for (const file of staged.files[table])
				if (!file.path.startsWith(`${this.plan.locations[table]}/data/`))
					throw new Error(`${file.path} is not in the storage of ${table}`);
		this.leases.delete(staged.chunk);
		this.recordStaged(staged);
		return true;
	}

	/** Gives a failed chunk back to the queue, unless it failed MAX_ATTEMPTS times. Ignored from an old lease. */
	fail(lease: string, failure: Failure): boolean {
		const held = this.leases.get(failure.chunk);
		if (!held || held.lease !== lease) return false;
		this.leases.delete(failure.chunk);
		this.recordFailure(failure);
		if (!this.failed.has(failure.chunk)) this.pending.push(failure.chunk);
		return true;
	}

	/** The staged chunks of table to commit next, up to maxChunks, unless one is being committed. */
	batch(table: string, maxChunks: number): Batch | undefined {
		const waiting = this.waiting.get(table)!;
		if (this.committing.has(table) || !waiting.length) return undefined;
		const batch: Batch = { table, chunks: [], files: [], rows: 0 };
		for (const id of waiting.slice(0, maxChunks)) {
			batch.chunks.push(id);
			for (const file of this.staged.get(id)!.files[table]) {
				batch.files.push(file);
				batch.rows += file.rows;
			}
		}
		this.committing.add(table);
		return batch;
	}

	commitDone(record: Committed, now: number): void {
		this.committing.delete(record.table);
		this.recordCommitted(record, now);
	}

	commitFailed(failure: CommitFailure): void {
		this.committing.delete(failure.table);
		this.failures.push(failure);
		if (this.failures.length > RECENT) this.failures.shift();
	}

	status(now: number): QueueStatus {
		const committed = this.complete;
		const old = this.completions.findIndex((t) => t > now - RATE_WINDOW_MS);
		this.completions.splice(0, old === -1 ? this.completions.length : old);
		const recent = this.completions.length;
		const chunksPerMinute = recent ? recent / (RATE_WINDOW_MS / 60_000) : undefined;
		const remaining = this.plan.chunks.length - committed - this.failed.size;
		const average = <T>(items: T[], pick: (item: T) => number) =>
			items.reduce((s, item) => s + pick(item), 0) / items.length;
		return {
			chunks: this.plan.chunks.length,
			committed,
			staged: this.staged.size - committed,
			leased: this.leases.size,
			failed: this.failed.size,
			rows: { ...this.rows },
			chunksPerMinute,
			remainingMinutes: chunksPerMinute ? Math.round(remaining / chunksPerMinute) : undefined,
			averageSeconds: this.recentStaged.length
				? {
						generate: average(this.recentStaged, (s) => s.generate_seconds),
						write: average(this.recentStaged, (s) => s.write_seconds)
					}
				: undefined,
			commits: this.plan.tables.map((table) => {
				const commits = this.recentCommits.filter((c) => c.table === table);
				return {
					table,
					commits: commits.length,
					averageChunks: commits.length ? average(commits, (c) => c.chunks.length) : 0,
					averageSeconds: commits.length ? average(commits, (c) => c.seconds) : 0
				};
			}),
			failures: this.failures.slice(-10)
		};
	}

	/** Every chunk is committed or failed for good; a failed chunk is never staged, so none is both. */
	get finished(): boolean {
		return this.complete + this.failed.size === this.plan.chunks.length;
	}

	private reclaim(now: number): void {
		for (const [id, held] of this.leases)
			if (held.expires <= now) {
				this.leases.delete(id);
				this.pending.push(id);
			}
	}

	private recordStaged(staged: Staged): void {
		this.staged.set(staged.chunk, staged);
		for (const table of this.plan.tables) this.waiting.get(table)!.push(staged.chunk);
		this.recentStaged.push(staged);
		if (this.recentStaged.length > RECENT) this.recentStaged.shift();
	}

	private recordCommitted(record: Committed, at: number): void {
		const done = new Set(record.chunks);
		this.waiting.set(
			record.table,
			this.waiting.get(record.table)!.filter((id) => !done.has(id))
		);
		for (const id of record.chunks) {
			const tables = this.committed.get(id) ?? new Set<string>();
			if (tables.has(record.table)) continue;
			tables.add(record.table);
			this.committed.set(id, tables);
			if (tables.size < this.plan.tables.length) continue;
			this.complete++;
			this.completions.push(at);
		}
		this.rows[record.table] = (this.rows[record.table] ?? 0) + record.rows;
		this.recentCommits.push(record);
		if (this.recentCommits.length > RECENT) this.recentCommits.shift();
	}

	private recordFailure(failure: Failure): void {
		const attempts = (this.attempts.get(failure.chunk) ?? 0) + 1;
		this.attempts.set(failure.chunk, attempts);
		if (attempts >= MAX_ATTEMPTS) this.failed.add(failure.chunk);
		this.failures.push(failure);
		if (this.failures.length > RECENT) this.failures.shift();
	}
}
